/**
 * FFmpeg's built-in `atempo` filter accepts values in [0.5, 2.0].
 * Values outside that range must be chained (e.g., 2.5 -> atempo=2.0,atempo=1.25).
 */
export function buildAtempoChain(speed: number, useRubberband = false): string {
  const safeSpeed = Math.max(0.25, Math.min(4.0, speed));
  if (useRubberband) {
    return `rubberband=tempo=${safeSpeed.toFixed(4)}`;
  }

  const filters: string[] = [];
  let remaining = safeSpeed;

  while (remaining > 2.0) {
    filters.push('atempo=2.0');
    remaining /= 2.0;
  }
  while (remaining < 0.5) {
    filters.push('atempo=0.5');
    remaining /= 0.5;
  }
  filters.push(`atempo=${remaining.toFixed(4)}`);
  return filters.join(',');
}

/**
 * Generates a runnable FFmpeg shell script implementing per-segment atempo fitting,
 * adelay SRT placement, and BGM gap-fill / dialogue ducking.
 */
export function generateFfmpegCommand(params: {
  media: ProjectMediaState;
  segments: DubSegment[];
  bgm: BgmConfig;
  useRubberband: boolean;
}): string {
  const { media, segments, bgm, useRubberband } = params;
  const videoIn = media.videoFileName || 'movie.mp4';
  const dubIn = media.dubMasterFileName || 'dubbed_audio.wav';
  const bgmIn = bgm.fileName || 'background_music.mp3';

  const activeSegs = segments.filter((s) => s.hasAudio && !s.muted);
  const hasSeparateClips = activeSegs.some((s) => s.clipBuffer && s.clipFileName !== media.dubMasterFileName);

  const inputs: string[] = [`-i "${videoIn}"`];
  let dubInputIndex = 1;
  const clipInputMap = new Map<string, number>();

  if (!hasSeparateClips) {
    inputs.push(`-i "${dubIn}"`);
  } else {
    activeSegs.forEach((seg) => {
      const key = seg.clipFileName || dubIn;
      if (!clipInputMap.has(key)) {
        clipInputMap.set(key, inputs.length);
        inputs.push(`-i "${key}"`);
      }
    });
    dubInputIndex = 1;
  }

  const bgmInputIndex = inputs.length;
  if (bgm.fileName) {
    inputs.push(`${bgm.loop ? '-stream_loop -1 ' : ''}-i "${bgmIn}"`);
  }

  const filterLines: string[] = [];
  const segLabels: string[] = [];

  activeSegs.forEach((seg, idx) => {
    const inputIdx = hasSeparateClips
      ? (clipInputMap.get(seg.clipFileName || dubIn) ?? dubInputIndex)
      : dubInputIndex;

    const srcStart = seg.sourceStartSec.toFixed(3);
    const srcEnd = seg.sourceEndSec.toFixed(3);
    const delayMs = Math.max(0, Math.round(seg.startSec * 1000));
    const tempoChain = buildAtempoChain(seg.atempo, useRubberband);
    const volFilter = Math.abs(seg.gain - 1) > 0.02 ? `,volume=${seg.gain.toFixed(2)}` : '';

    const label = `d${idx}`;
    segLabels.push(`[${label}]`);
    filterLines.push(
      `  [${inputIdx}:a]atrim=start=${srcStart}:end=${srcEnd},asetpts=PTS-STARTPTS,${tempoChain}${volFilter},adelay=${delayMs}|${delayMs}[${label}]`
    );
  });

  if (segLabels.length > 0) {
    filterLines.push(
      `  ${segLabels.join('')}amix=inputs=${segLabels.length}:duration=longest:dropout_transition=0:normalize=0[dub_mix]`
    );
  } else {
    filterLines.push(`  anullsrc=r=44100:cl=stereo:d=${Math.max(1, media.videoDurationSec).toFixed(2)}[dub_mix]`);
  }

  if (bgm.fileName && !bgm.muted) {
    // Build dynamic volume expression: full gapVolume in dialogue-free gaps, duckVolume during SRT cues
    const activeConditions = activeSegs
      .map((s) => `between(t,${s.startSec.toFixed(3)},${s.endSec.toFixed(3)})`)
      .join('+');

    const bgmStartTrim = bgm.offsetSec > 0 ? `atrim=start=${bgm.offsetSec.toFixed(3)},asetpts=PTS-STARTPTS,` : '';
    const volumeExpr = activeConditions
      ? `volume='if(${activeConditions},${bgm.duckVolume.toFixed(2)},${bgm.gapVolume.toFixed(2)})':eval=frame`
      : `volume=${bgm.gapVolume.toFixed(2)}`;

    filterLines.push(
      `  [${bgmInputIndex}:a]${bgmStartTrim}atrim=0:${Math.max(1, media.videoDurationSec).toFixed(3)},asetpts=PTS-STARTPTS,${volumeExpr}[bgm_ducked]`
    );
    filterLines.push(
      `  [dub_mix][bgm_ducked]amix=inputs=2:duration=first:normalize=0[master_audio]`
    );
  } else {
    filterLines.push(`  [dub_mix]anull[master_audio]`);
  }

  return [
    `#!/usr/bin/env bash`,
    `# Generated by DubSync Studio — Per-Segment ${useRubberband ? 'Rubberband' : 'atempo'} + BGM Gap-Fill`,
    `# Compatible with Linux, macOS, Windows Git Bash, and Android Termux (pkg install ffmpeg)`,
    ``,
    `ffmpeg -y \\`,
    `  ${inputs.join(' \\\n  ')} \\`,
    `  -filter_complex "\\`,
    filterLines.join('; \\\n'),
    `" \\`,
    `  -map 0:v:0 -map "[master_audio]" \\`,
    `  -c:v copy -c:a aac -b:a 192k -shortest \\`,
    `  "dubbed_${videoIn.replace(/\.[^.]+$/, '')}.mp4"`,
  ].join('\n');
}

/**
 * Generates Final Cut Pro XML (FCPXML 1.9) importable into DaVinci Resolve and Premiere Pro.
 */
export function generateFcpxml(params: {
  media: ProjectMediaState;
  segments: DubSegment[];
  bgm: BgmConfig;
}): string {
  const { media, segments, bgm } = params;
  const totalSec = Math.max(1, media.videoDurationSec);
  const videoName = escapeXml(media.videoFileName || 'movie.mp4');
  const dubName = escapeXml(media.dubMasterFileName || 'dubbed_audio.wav');
  const bgmName = escapeXml(bgm.fileName || 'background_music.mp3');

  const toRational = (sec: number) => `${Math.round(sec * 1000)}/1000s`;

  const dubClipsXml = segments
    .filter((s) => s.hasAudio && !s.muted)
    .map((seg) => {
      const targetDur = Math.max(0.05, seg.endSec - seg.startSec);
      const srcDur = Math.max(0.05, seg.sourceEndSec - seg.sourceStartSec);
      const clipName = escapeXml(seg.clipFileName || `Line_${seg.index}`);
      return `            <asset-clip name="${clipName} (${seg.atempo.toFixed(2)}x)" ref="r2" lane="1" offset="${toRational(seg.startSec)}" start="${toRational(seg.sourceStartSec)}" duration="${toRational(targetDur)}">
              <timeMap>
                <timept time="0s" value="${toRational(seg.sourceStartSec)}" interp="linear"/>
                <timept time="${toRational(targetDur)}" value="${toRational(seg.sourceStartSec + srcDur)}" interp="linear"/>
              </timeMap>
              <note>${escapeXml(seg.text)}</note>
            </asset-clip>`;
    })
    .join('\n');

  const bgmXml = bgm.fileName
    ? `            <asset-clip name="${bgmName} (BGM Gap-Fill)" ref="r3" lane="-1" offset="0s" start="${toRational(bgm.offsetSec)}" duration="${toRational(totalSec)}"/>`
    : '';

  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE fcpxml>
<fcpxml version="1.9">
  <resources>
    <format id="r0" name="FFVideoFormat1080p24" frameDuration="100/2400s" width="1920" height="1080"/>
    <asset id="r1" name="${videoName}" start="0s" duration="${toRational(totalSec)}" hasVideo="1" hasAudio="1"/>
    <asset id="r2" name="${dubName}" start="0s" duration="${toRational(totalSec)}" hasAudio="1"/>
    ${bgm.fileName ? `<asset id="r3" name="${bgmName}" start="0s" duration="${toRational(bgm.buffer?.duration || totalSec)}" hasAudio="1"/>` : ''}
  </resources>
  <library>
    <event name="DubSync Project">
      <project name="SRT_Synced_Dub">
        <sequence format="r0" duration="${toRational(totalSec)}">
          <spine>
            <asset-clip name="${videoName}" ref="r1" offset="0s" duration="${toRational(totalSec)}">
${dubClipsXml}
${bgmXml}
            </asset-clip>
          </spine>
        </sequence>
      </project>
    </event>
  </library>
</fcpxml>`;
}

export function generateTimelineJson(params: {
  media: ProjectMediaState;
  segments: DubSegment[];
  bgm: BgmConfig;
}): string {
  const { media, segments, bgm } = params;
  return JSON.stringify(
    {
      project: 'DubSync Studio Timeline',
      video: {
        fileName: media.videoFileName,
        durationSec: Number(media.videoDurationSec.toFixed(3)),
      },
      dubMode: media.dubMode,
      pitchPreserve: media.pitchPreserve,
      bgm: {
        fileName: bgm.fileName,
        gapVolume: bgm.gapVolume,
        duckVolume: bgm.duckVolume,
        duckFadeMs: bgm.duckFadeMs,
        loop: bgm.loop,
      },
      dialogueSegments: segments.map((s) => ({
        index: s.index,
        srtStart: formatSrtTimestamp(s.startSec),
        srtEnd: formatSrtTimestamp(s.endSec),
        targetStartSec: Number(s.startSec.toFixed(3)),
        targetEndSec: Number(s.endSec.toFixed(3)),
        sourceStartSec: Number(s.sourceStartSec.toFixed(3)),
        sourceEndSec: Number(s.sourceEndSec.toFixed(3)),
        atempo: s.atempo,
        muted: s.muted,
        gain: s.gain,
        text: s.text,
      })),
    },
    null,
    2
  );
}

export function generateUpdatedSrt(segments: DubSegment[]): string {
  return serializeSrt(segments);
}

/**
 * Triggers a browser file download from a Blob or string.
 */
export function downloadFile(content: Blob | string, filename: string, mimeType = 'text/plain') {
  const blob = content instanceof Blob ? content : new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

function escapeXml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}
